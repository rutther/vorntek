CREATE FUNCTION reject_runtime_snapshot_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'runtime snapshots are append-only'; END $$;
CREATE TRIGGER immutable_runtime_revision BEFORE UPDATE OR DELETE ON marketing_runtime_revision
    FOR EACH ROW EXECUTE FUNCTION reject_runtime_snapshot_mutation();
CREATE TRIGGER immutable_measurement_route BEFORE UPDATE OR DELETE ON lead_measurement_route
    FOR EACH ROW EXECUTE FUNCTION reject_runtime_snapshot_mutation();

CREATE FUNCTION validate_runtime_ownership() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE owned_site bigint; owned_env varchar(16); asset_site bigint; asset_env varchar(16); asset_pixel varchar(255);
BEGIN
    SELECT l.site_id,l.environment INTO owned_site,owned_env FROM marketing_loop l
      WHERE l.id=(SELECT loop_id FROM marketing_runtime_binding WHERE id=NEW.binding_id);
    SELECT site_id,environment,public_id INTO asset_site,asset_env,asset_pixel
      FROM marketing_integration WHERE id=NEW.integration_id;
    IF owned_site IS DISTINCT FROM NEW.site_id OR asset_site IS DISTINCT FROM NEW.site_id
       OR owned_env IS DISTINCT FROM NEW.environment OR asset_env IS DISTINCT FROM NEW.environment
       OR asset_pixel IS DISTINCT FROM NEW.pixel_id THEN
        RAISE EXCEPTION 'runtime ownership mismatch';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER runtime_ownership BEFORE INSERT ON marketing_runtime_revision
    FOR EACH ROW EXECUTE FUNCTION validate_runtime_ownership();

CREATE FUNCTION protect_pixel_identity() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.integration_type='pixel' AND (OLD.public_id IS DISTINCT FROM NEW.public_id
        OR OLD.site_id IS DISTINCT FROM NEW.site_id OR OLD.environment IS DISTINCT FROM NEW.environment
        OR OLD.routing_mode IS DISTINCT FROM NEW.routing_mode OR OLD.provider_id IS DISTINCT FROM NEW.provider_id
        OR OLD.integration_type IS DISTINCT FROM NEW.integration_type) THEN
        RAISE EXCEPTION 'pixel identity is immutable; create another integration';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER immutable_pixel_identity BEFORE UPDATE ON marketing_integration
    FOR EACH ROW EXECUTE FUNCTION protect_pixel_identity();
